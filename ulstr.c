#include<unistd.h>

int main(int argc, char **argv)
{
	if (argc != 2)
	{
		write (1, "\n", 1);
		return (0);
	}
	char	*s		=	argv[1];
	int		i		=	0;
	char	c;

	while (s[i] != '\0')
	{
		c = s[i];
		if (s[i] >= 'a' && s[i] <= 'z')
			c = s[i] - 32;
		else if (s[i] >= 'A' && s[i] <= 'Z')
			c = s[i] + 32;
		write (1, &c, 1);
		i++;
	}
	return (0);
}